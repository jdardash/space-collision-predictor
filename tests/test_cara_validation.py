def test_two_body_propagation_conserves_energy_and_reverses():
    r0 = np.array([7000.0, 100.0, -200.0])
    v0 = np.array([0.5, 7.4, 0.9])
    r1, v1 = propagate_two_body(r0, v0, 1800.0)

    def energy(r, v):
        return 0.5 * float(v @ v) - EARTH_MU_KM3_S2 / float(np.linalg.norm(r))

    assert energy(r1, v1) == pytest.approx(energy(r0, v0), rel=1e-11)
    back_r, back_v = propagate_two_body(r1, v1, -1800.0)
    np.testing.assert_allclose(back_r, r0, rtol=1e-9, atol=1e-9)
    np.testing.assert_allclose(back_v, v0, rtol=1e-9, atol=1e-9)


def test_recovered_tca_shift_is_sub_millisecond(comparisons):
    """CDM epochs are rounded to the millisecond, so the true TCA is within half of one.

    A shift materially larger than that would mean the propagation or the
    minimiser is wrong, not that the message was rounded.
    """
    shifts = [abs(c.tca_shift_s) for c in comparisons]
    assert max(shifts) < 1e-3, f"largest shift {max(shifts):.3e} s exceeds CDM epoch rounding"


def test_recovered_tca_is_a_true_minimum_of_range(by_case):
    """Range must increase on both sides of the recovered TCA."""
    case_id = CASE_IDS[0]
    cdm = read_cara_cdm(fixture_dir() / "cdms" / f"{case_id}.cdm")
    dt, r1, _, r2, _ = find_true_tca(
        cdm.position1_km, cdm.velocity1_km_s, cdm.position2_km, cdm.velocity2_km_s
    )
    at_tca = float(np.linalg.norm(r1 - r2))
    for offset in (-1e-2, 1e-2, -1.0, 1.0):
        a, _ = propagate_two_body(cdm.position1_km, cdm.velocity1_km_s, dt + offset)
        b, _ = propagate_two_body(cdm.position2_km, cdm.velocity2_km_s, dt + offset)
        assert float(np.linalg.norm(a - b)) >= at_tca


def test_two_body_tca_agrees_with_caras_linear_formula(by_case):
    """CARA's released FindNearbyCA.m only implements straight-line motion.

    Its TWOBODY branch raises "not implemented", so the reference values were
    produced with dTCA = -(dr . dv) / |dv|^2 (FindNearbyCA.m, LINEAR mode).
    Over a sub-millisecond shift the two objects' gravitational accelerations
    very nearly cancel in the relative frame, so our two-body solution must
    reproduce the linear one; this test is what licenses comparing our numbers
    against theirs at all.
    """
    for case_id in CASE_IDS[:8]:
        cdm = read_cara_cdm(fixture_dir() / "cdms" / f"{case_id}.cdm")
        dr = cdm.position1_km - cdm.position2_km
        dv = cdm.velocity1_km_s - cdm.velocity2_km_s
        linear_dt = -float(dr @ dv) / float(dv @ dv)
        two_body_dt, _, _, _, _ = find_true_tca(
            cdm.position1_km, cdm.velocity1_km_s, cdm.position2_km, cdm.velocity2_km_s
        )
        assert two_body_dt == pytest.approx(linear_dt, abs=1e-9)


