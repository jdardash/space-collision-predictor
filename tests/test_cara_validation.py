def test_encounter_projection_matches_the_probability_module(by_case):
    """sda.cara rebuilds the B-plane basis instead of importing a private symbol.

    sda.probability._rotation_matrix_to_conjunction_plane is private and owned
    elsewhere, so cara.py carries its own copy. This pins the copy to the
    original: the 2x2 covariance projected here must equal the one
    project_covariance_to_encounter_plane returns.
    """
    for case_id in CASE_IDS[:5]:
        cdm = read_cara_cdm(fixture_dir() / "cdms" / f"{case_id}.cdm")
        _, r1, v1, r2, v2 = find_true_tca(
            cdm.position1_km, cdm.velocity1_km_s, cdm.position2_km, cdm.velocity2_km_s
        )
        combined = cdm.combined_covariance_eci_km2()
        _, ours = encounter_geometry(r1, v1, r2, v2, combined)
        theirs = probability.project_covariance_to_encounter_plane(combined, v1 - v2)
        np.testing.assert_allclose(ours, theirs, rtol=1e-12, atol=1e-24)


def test_cara_tolerance_ladder_matches_isclose_m():
    """isclose.m: abs(a-b) <= max(tol, tol*max(abs(a),abs(b)))."""
    assert cara_tolerance_band(1.0, 1.0) == "Exact"
    # 1.0 + 1e-16 is not representable (double eps is 2.22e-16); use a step
    # that survives rounding but still lands inside the 1e-15 band.
    assert cara_tolerance_band(1.0, 1.0 + 5e-16) == "VeryTight"
    assert cara_tolerance_band(1.0, 1.0 + 1e-13) == "Tight"
    assert cara_tolerance_band(1.0, 1.0 + 1e-9) == "Loose"
    assert cara_tolerance_band(1.0, 1.0 + 1e-4) == "VeryLoose"
    assert cara_tolerance_band(1.0, 2.0) == "NoMatch"


