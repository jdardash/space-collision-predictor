def _largest_pc_cases(count: int = 5) -> list[str]:
    rows = sorted(load_reference_rows(), key=lambda r: r.pc2d, reverse=True)
    return [r.conjunction_id for r in rows[:count]]


@pytest.mark.parametrize("case_id", _largest_pc_cases())
def test_monte_carlo_brackets_the_sdmc_interval(case_id):
    """Our sampler against CARA's PcSDMCLo/PcSDMCHi 95 percent interval.

    Two sources of scatter have to be allowed for, and only one of them is in
    CARA's published bounds. Theirs covers their sampling noise; ours adds
    binomial noise of our own, sqrt(p(1-p)/n), which at 1e6 samples and
    p around 2e-4 is roughly 7 percent of p. Widening their interval by three
    of our standard errors is the honest comparison. The seed is fixed so the
    test is deterministic; it is not tuned, and the assertion holds across
    seeds because the padding is derived rather than fitted.
    """
    from sda.cara import compare_case

    row = next(r for r in load_reference_rows() if r.conjunction_id == case_id)
    case = compare_case(row, mc_samples=MC_SAMPLES, mc_seed=DEFAULT_MC_SEED)

    assert case.monte_carlo_samples == MC_SAMPLES, "case should be resolvable at 1e6 samples"
    assert case.sdmc_interval_contains("monte_carlo", MC_SIGMA_MULTIPLE), (
        f"{case_id}: ours {case.ours['monte_carlo']:.6e} outside "
        f"[{case.reference['pc_sdmc_lo']:.6e}, {case.reference['pc_sdmc_hi']:.6e}] "
        f"widened by {MC_SIGMA_MULTIPLE} sigma"
    )


def test_monte_carlo_agrees_with_foster_on_the_largest_case():
    """Sanity: the sampler and the quadrature must agree with each other too."""
    from sda.cara import compare_case

    row = max(load_reference_rows(), key=lambda r: r.pc2d)
    case = compare_case(row, mc_samples=MC_SAMPLES, mc_seed=DEFAULT_MC_SEED)
    foster = case.ours["foster"]
    monte_carlo = case.ours["monte_carlo"]
    sigma = math.sqrt(monte_carlo * (1.0 - monte_carlo) / MC_SAMPLES)
    assert abs(monte_carlo - foster) <= 4.0 * sigma


# ---------------------------------------------------------------------------
# Modelling truth: 2D against CARA's 3D supervised Monte Carlo.
# The 29 cases CARA flags are xfail with its own stated reason.
# ---------------------------------------------------------------------------


def _truth_params():
    params = []
    for case_id in CASE_IDS:
        reason = FLAGGED.get(case_id)
        if reason:
            # strict=True on purpose: these fail decisively (smallest observed
            # error 3.47e-01 against a 5e-02 tolerance), so if one ever starts
            # passing, the corpus or our method changed and we want to be told.
            marks = [pytest.mark.xfail(strict=True, reason=f"CARA: {reason}")]
            params.append(pytest.param(case_id, marks=marks))
        else:
            params.append(pytest.param(case_id))
    return params


@pytest.mark.parametrize("case_id", _truth_params())
def test_2d_pc_tracks_the_3d_monte_carlo_truth(case_id, by_case):
    """Does the 2D method actually predict what a full 3D simulation finds?

    For the 24 conjunctions CARA does not flag, yes, to within a few percent.
    For the other 29 it does not, and CARA says why in its own Comment column,
    which is carried into the xfail reason for each one. Those cases are the
    documented boundary of the 2D method: short encounters, high relative
    curvature, or a Pc large enough that the linear approximation of the
    relative trajectory stops holding.
    """
    case = by_case[case_id]
    truth = case.reference["pc_sdmc"]
    if not (math.isfinite(truth) and truth > 0.0):
        pytest.skip("no supervised Monte Carlo reference for this conjunction")
    ours = case.ours["foster"]
    relative = abs(ours - truth) / max(ours, truth)
    assert relative <= MODELLING_TOLERANCE_VS_3D, (
        f"{case_id}: 2D Pc {ours:.6e} vs 3D truth {truth:.6e} "
        f"(relative {relative:.3e})"
    )


def test_the_flagged_population_is_the_size_cara_documents():
    """29 of 53 carry a method-usage violation; guards the xfail list itself.

    Without this, silently losing the Comment column would turn every xfail
    into a passing test and the suite would look better for it.
    """
    assert len(FLAGGED) == 29
    assert all(reason for reason in FLAGGED.values()), "every flagged case needs a stated reason"
    rows = load_reference_rows()
    assert sum(1 for r in rows if r.pc2d_is_valid) == 24


def test_unflagged_cases_mostly_sit_inside_the_sdmc_interval(comparisons):
    """Aggregate check on the 24 valid cases; two sit just outside at about 2e-2."""
    valid = [c for c in comparisons if c.pc2d_is_valid]
    inside = sum(1 for c in valid if c.sdmc_interval_contains("foster"))
    assert inside >= 20, f"only {inside}/{len(valid)} unflagged cases inside the 95 percent CI"


