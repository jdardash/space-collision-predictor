from sda.constants import EARTH_MU_KM3_S2

# pc_alfano arrived in sda.probability after this tier was written; look it up
# at runtime so the file works either way.
_PC_ALFANO = getattr(probability, "pc_alfano", None)

#: Our Foster against CARA's Pc2D. Both implement the same method, so this is
#: parity, not physics: CARA's own widest acceptable band
#: (ComparePc2D_to_CARAValues.m line 23, "VeryLoose") is 1e-3, and we clear it
#: on every case with room to spare (worst observed 4.93e-05).
PARITY_RELATIVE_TOLERANCE = 1e-3

#: Our Foster against CARA's 3D supervised Monte Carlo, for the cases CARA does
#: NOT flag. This is the 2D linear-relative-motion modelling error, measured at
#: worst 2.01e-02 across the 24 unflagged cases. 5e-2 leaves headroom while
#: staying far below the 3.47e-01 minimum error of the flagged cases, so the
#: tolerance genuinely separates "2D is valid here" from "2D is not".
MODELLING_TOLERANCE_VS_3D = 5e-2

#: Chan's series is not a tight oracle. Measured across all 53 cases the ratio
#: chan/CARA_Pc2D spans 0.0136 to 1.1501, and it is not monotonic in the
#: encounter-plane aspect ratio, so only a wide band is defensible globally.
CHAN_RATIO_MIN = 0.010
CHAN_RATIO_MAX = 1.25

#: Chan does behave on near-circular encounter-plane covariances. Restricted to
#: the 7 cases whose 2x2 covariance aspect ratio is at most 15 it lands within
#: 20 percent (measured worst about 12 percent).
CHAN_ISOTROPIC_ASPECT_RATIO = 15.0
CHAN_ISOTROPIC_TOLERANCE = 0.20

#: Monte Carlo needs enough expected hits to be worth asserting on.
MC_SAMPLES = 1_000_000
MC_SIGMA_MULTIPLE = 3.0


