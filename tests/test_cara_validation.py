@pytest.mark.parametrize("case_id", CASE_IDS)
def test_chan_stays_within_its_documented_band(case_id, by_case):
    """Chan's equivalent-area series is bounded, not accurate, on this corpus.

    Measured over all 53 cases the ratio chan/CARA_Pc2D runs from 0.0136 to
    1.1501: the series truncates badly when the encounter-plane covariance is
    highly elongated, which most real conjunctions are. The band below is a
    regression fence around the measured spread, not a claim of accuracy, and
    it is deliberately one-sided-tight at the top because Chan overestimating
    by more than a quarter would be a new failure mode.
    """
    case = by_case[case_id]
    if case.expected_pc2d <= 0.0:
        pytest.skip("reference Pc2D is zero; a ratio is undefined")
    ratio = case.ours["chan"] / case.expected_pc2d
    assert CHAN_RATIO_MIN <= ratio <= CHAN_RATIO_MAX, (
        f"{case_id}: chan/CARA = {ratio:.4f} left the documented band"
    )


def test_chan_is_accurate_on_near_isotropic_covariances(by_case):
    """Where the series assumption holds, Chan should be close, not merely bounded."""
    checked = 0
    for case_id in CASE_IDS:
        cdm = read_cara_cdm(fixture_dir() / "cdms" / f"{case_id}.cdm")
        _, r1, v1, r2, v2 = find_true_tca(
            cdm.position1_km, cdm.velocity1_km_s, cdm.position2_km, cdm.velocity2_km_s
        )
        _, cov_2d = encounter_geometry(r1, v1, r2, v2, cdm.combined_covariance_eci_km2())
        eigenvalues = np.linalg.eigvalsh(cov_2d)
        aspect_ratio = math.sqrt(max(eigenvalues) / max(min(eigenvalues), 1e-30))
        if aspect_ratio > CHAN_ISOTROPIC_ASPECT_RATIO:
            continue
        case = by_case[case_id]
        checked += 1
        assert case.relative_error("chan") <= CHAN_ISOTROPIC_TOLERANCE, (
            f"{case_id}: aspect ratio {aspect_ratio:.1f}, "
            f"chan relative error {case.relative_error('chan'):.3f}"
        )
    assert checked >= 5, "expected at least 5 near-isotropic cases in the corpus"


