"""External validation of our Pc code against NASA CARA reference values.

These are not unit tests of our own arithmetic. Every expected number here was
produced by someone else's independently written and operationally used code
(NASA CARA Analysis Tools, github.com/nasa/CARA_Analysis_Tools at 86ba28a,
NASA Open Source Agreement v1.3), so a failure means our answer disagrees with
the reference implementation rather than with our own past behaviour.

Two different questions get asked, and keeping them apart is the whole point of
the file:

* Does our 2D-Pc reproduce CARA's 2D-Pc? That is a code-parity question. Both
  sides run the same method on the same covariances, so agreement should be
  near machine precision, and all 53 cases are asserted at CARA's own
  tolerance ladder.
* Does our 2D-Pc reproduce physical truth, represented by CARA's supervised
  direct Monte Carlo? That is a modelling question, and for 29 of the 53 cases
  CARA's own notes say the answer is no because the 2D method is being used
  outside its validity. Those are xfail with CARA's documented reason attached,
  never skipped: the reason travels with the test, and strict=True means the
  day one of them starts passing the suite says so instead of staying quiet.

Fixtures come from tests/data/cara, regenerated by scripts/import_cara_fixtures.py.
"""

from __future__ import annotations

